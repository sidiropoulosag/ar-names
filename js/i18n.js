// t('key', {name: 'Μαρία'}) -> text in the current language (fallback: English, then Greek, then the key)
export function t(key, params = {}) {
  let v = D[lang] && D[lang][key];
  if (v === undefined) v = D.en[key] !== undefined ? D.en[key] : D.el[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : m));
}
export const has = (key) => D.el[key] !== undefined;

// Static texts in the HTML: data-i18n (text), data-i18n-html, data-i18n-ph (placeholder),
// data-i18n-aria (aria-label), data-i18n-title (title)
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  document.documentElement.lang = lang;
  document.title = t('app.title');
}
// change the language: saved, applied to the page at once, then 'langchange' lets the app redraw its dynamic texts
export function setLang(l) {
  if (!isLang(l)) return;
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch (_) {}
  applyI18n(document);
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: l } }));
}
