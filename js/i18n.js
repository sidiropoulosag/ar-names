// best guess from the browser (used to preselect on the first-run screen)
export function guessLang() {
  const list = [...(navigator.languages || []), navigator.language || ''].map((x) => String(x).toLowerCase().slice(0, 2));
  return list.find(isLang) || 'en';
}
